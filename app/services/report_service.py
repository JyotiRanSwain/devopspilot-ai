"""Build Markdown and JSON diagnostic reports. Everything is redacted again on the way out."""
import json
from datetime import datetime, timezone

from app.core.redaction import redact
from app.services.investigation import Investigation


def from_investigation(inv: Investigation) -> dict:
    c = inv.container
    return {
        "title": f"Diagnostic report: {c.name}",
        "generated_at": datetime.now(timezone.utc).isoformat(timespec="seconds"),
        "resource": c.name,
        "source": "live Docker inspection",
        "status": None,
        "summary": f"{len(inv.findings)} finding(s) from {len(inv.window.lines)} log lines.",
        "evidence": [f"status={c.status}", f"health={c.health or 'n/a'}", f"restart_count={c.restart_count}",
                     f"exit_code={c.exit_code if c.exit_code is not None else 'n/a'}", f"image={c.image}"],
        "findings": [f.model_dump() for f in inv.findings],
        "actions": list(dict.fromkeys(s for f in inv.findings for s in f.next_steps)),
    }


def from_incident(incident: dict) -> dict:
    return {
        "title": incident["title"], "generated_at": datetime.now(timezone.utc).isoformat(timespec="seconds"),
        "resource": incident.get("resource"), "source": "stored incident", "status": incident["status"],
        "created_at": incident["created_at"], "resolution_note": incident.get("resolution_note"),
        "summary": incident.get("summary") or "", "evidence": incident["evidence"],
        "findings": incident["findings"], "actions": incident["actions"],
    }


def to_json(report: dict) -> str:
    return redact(json.dumps(report, indent=2, default=str))


def to_markdown(report: dict) -> str:
    out = [f"# {report['title']}", "",
           f"- Generated: {report['generated_at']}", f"- Resource: {report.get('resource') or 'unknown'}",
           f"- Source: {report['source']}"]
    if report.get("status"):
        out.append(f"- Status: {report['status']} (set by a person; never inferred)")
    out += ["", "## Summary", report.get("summary") or "No summary.", "", "## Observed evidence (verified)"]
    out += [f"- {e}" for e in report["evidence"]] or ["- none"]
    out += ["", "## Findings"]
    for f in report["findings"]:
        out += ["", f"### {f['rule_id']}: {f['title']}", f"Severity: {f['severity']} | Confidence: {f['confidence']}", "", "Evidence:"]
        out += [f"- {e}" for e in f.get("evidence", [])]
        out += ["", "Possible causes (hypotheses):"] + [f"- {c}" for c in f.get("possible_causes", [])]
    if not report["findings"]:
        out.append("No known failure patterns were detected.")
    out += ["", "## Recommended next steps"] + [f"- {a}" for a in report["actions"]]
    if report.get("resolution_note"):
        out += ["", "## Resolution note", report["resolution_note"]]
    out += ["", "_Generated by DevOpsPilot AI. Nothing in this report was executed automatically._", ""]
    return redact("\n".join(out))
